import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
async function files(dir) {
  const result = [];
  for (const entry of await readdir(path.join(root, dir), { withFileTypes: true })) {
    const name = `${dir}/${entry.name}`;
    if (entry.isDirectory()) result.push(...await files(name));
    else if (entry.isFile() && /\.(html|js|css|svg|webmanifest)$/.test(entry.name)) result.push(name);
  }
  return result;
}
export async function manifest() {
  const paths = ['index.html', ...(await files('public'))].sort();
  if (paths.length > 50) throw Error('Offline shell exceeds its 50 asset limit.');
  const assets = await Promise.all(paths.map(async file => ({ path: file, sha256: digest(await readFile(path.join(root, file))) })));
  const workerHash = digest(await readFile(path.join(root, 'sw.js')));
  return { version: digest(JSON.stringify({ assets, workerHash })), assets, workerHash };
}
export async function source() {
  const { version, assets, workerHash } = await manifest();
  return `// Generated by scripts/update-shell.mjs. Do not edit by hand.\nexport const SHELL_VERSION = ${JSON.stringify(version)};\nexport const SHELL_WORKER_HASH = ${JSON.stringify(workerHash)};\nexport const SHELL_ASSETS = Object.freeze(${JSON.stringify(assets, null, 2)});\n`;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = await source(), target = path.join(root, 'shell-manifest.js');
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8').catch(() => '') !== output) { console.error('Offline shell manifest is stale. Run node scripts/update-shell.mjs.'); process.exitCode = 1; }
  } else await writeFile(target, output);
}
