import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const files = ['contract.js','primitives.js'];
export async function syncHelpers({check=false}={}) {
  let clean=true;
  for (const file of files) {
    const expected='// GENERATED from packages/helpers. Do not edit this file.\n'+await readFile(new URL(`packages/helpers/${file}`,root),'utf8');
    const destination=new URL(`public/helpers/${file}`,root),actual=await readFile(destination,'utf8').catch(()=>'');
    if (actual===expected) continue;
    clean=false;
    if (!check) { await mkdir(new URL('public/helpers/',root),{recursive:true}); await writeFile(destination,expected); }
  }
  return clean;
}
if (process.argv[1]===fileURLToPath(import.meta.url)) {
  if (!await syncHelpers({check:process.argv.includes('--check')}) && process.argv.includes('--check')) {
    console.error('Generated helpers differ. Run node scripts/sync-helpers.mjs.'); process.exitCode=1;
  }
}
