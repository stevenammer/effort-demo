import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const files = ['ef.js', 'semantic.js', 'readable.js'];
const header = '// GENERATED from packages/core. Do not edit this file.\n';

export async function expectedCore(name) {
  return header + await readFile(join(root, 'packages/core', name), 'utf8');
}

export async function syncCore({ check = false } = {}) {
  let clean = true;
  for (const name of files) {
    const target = join(root, 'public/core', name);
    const expected = await expectedCore(name);
    const actual = await readFile(target, 'utf8').catch(() => '');
    if (actual === expected) continue;
    clean = false;
    if (!check) {
      await mkdir(join(root, 'public/core'), { recursive: true });
      await writeFile(target, expected);
    }
  }
  return clean;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const clean = await syncCore({ check: process.argv.includes('--check') });
  if (!clean && process.argv.includes('--check')) {
    console.error('public/core has drifted. Run node scripts/sync-core.mjs.');
    process.exitCode = 1;
  }
}
